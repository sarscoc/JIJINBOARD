import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {JSDOM} from 'jsdom';

test('recent updates persist locally and open the saved destination without fetching history',async t=>{
  const {window:w}=new JSDOM('<button id="boardActivityButton"></button><section id="boardActivity" hidden><p role="status"></p><ol></ol></section><iframe id="matrixFrame" data-ready="1"></iframe>',{url:'https://test/board/?id=room',runScripts:'outside-only'});
  t.after(()=>w.close());
  w.boardId='room';
  w.state={tool:'log',board:{participants:[{authorId:'pl',personaId:'pc',name:'禊彦',matrixIcon:'/api/boards/room/player-icons/matrix-icons/'+'a'.repeat(20)}]}};
  w.localStorage.setItem('trpgMarkerProfile',JSON.stringify({id:'pl',plName:'sars',plIcon:'/api/boards/room/player-icons/pl-icons/'+'c'.repeat(20)}));
  w.selectTool=tool=>{w.state.tool=tool};
  w.fetch=()=>assert.fail('activity must not fetch history');
  let opened;
  w.document.querySelector('iframe').contentWindow.jijinOpenActivity=row=>{opened=row;return true};
  for(const file of ['public/shared/comment-target.js','public/board/board-activity.js'])w.eval(readFileSync(file,'utf8'));
  const receive=detail=>w.dispatchEvent(new w.CustomEvent('jijinboard-activity',{detail}));
  receive({kind:'placement',id:'placed',templateId:'map',itemId:'participant:pl:pc',authorName:'sars'});
  receive({kind:'comment',id:'reply',target:'/boards/room/matrix/map/points/pc',authorName:'PC',icon:'/api/boards/room/player-icons/character-icons/'+'b'.repeat(20),reply:true});
  receive({kind:'comment',id:'reply',target:'/boards/room/matrix/map/points/pc'});
  receive({kind:'comment',id:'pl-comment',target:'/boards/room/matrix/map/points/pc',authorName:'sars'});
  const button=w.document.querySelector('#boardActivityButton');
  assert.ok(button.classList.contains('unread'));
  button.click();
  const panel=w.document.querySelector('#boardActivity');
  assert.equal(panel.hidden,false);
  assert.equal(button.getAttribute('aria-expanded'),'true');
  w.document.dispatchEvent(new w.KeyboardEvent('keydown',{key:'Escape'}));
  assert.equal(panel.hidden,true);
  button.click();
  w.document.body.dispatchEvent(new w.Event('pointerdown',{bubbles:true}));
  assert.equal(panel.hidden,true);
  button.click();
  const updates=w.document.querySelectorAll('li button');
  assert.equal(updates.length,3);
  assert.match(updates[1].textContent,/返信/);
  assert.match(updates[2].textContent,/MM · sarsが禊彦のコマを配置/);
  assert.match(updates[2].title,/sarsが禊彦のコマを配置/);
  assert.equal(panel.querySelector('time'),null);
  assert.equal(panel.querySelectorAll('li button.unread').length,3);
  assert.match(updates[1].querySelector('img').src,/character-icons/);
  assert.match(updates[2].querySelector('img').src,/matrix-icons/);
  assert.match(updates[0].querySelector('img').src,/pl-icons/);
  updates[1].click();
  await Promise.resolve();
  assert.equal(opened.id,'reply');
  assert.equal(opened.target.pointId,'pc');
  assert.equal(w.state.tool,'matrix');
  receive({kind:'comment',id:'reply',target:'/boards/room/matrix/map/points/pc'});
  button.click();
  assert.equal(panel.querySelectorAll('li button.unread').length,2);
  assert.equal(panel.querySelectorAll('li button')[1].classList.contains('unread'),false);
  receive({kind:'placement',id:'new',templateId:'map',itemId:'pc'});
  assert.equal(panel.querySelectorAll('li button.unread').length,3);
});

test('reconnected board merges missed updates by event time without duplicating updates',t=>{
  const {window:w}=new JSDOM('<button id="boardActivityButton"></button><section id="boardActivity" hidden><p role="status"></p><ol></ol></section>',{url:'https://test/board/?id=room',runScripts:'outside-only'});
  t.after(()=>w.close());
  w.boardId='room';
  w.state={tool:'log'};
  for(const file of ['public/shared/comment-target.js','public/board/board-activity.js'])w.eval(readFileSync(file,'utf8'));
  const receive=detail=>w.dispatchEvent(new w.CustomEvent('jijinboard-activity',{detail}));
  const update=(id,at)=>({kind:'placement',id,at,templateId:'map',itemId:'pc'});
  const button=w.document.querySelector('button');
  receive(update('live',3000));
  button.click();
  button.click();
  receive([update('live',3000),update('missed',2000)]);
  const {rows}=JSON.parse(w.localStorage.getItem('jijinboardActivity:room'));
  assert.deepEqual(rows.map(row=>[row.id,row.at,row.unread]),[['live',3000,true],['missed',2000,true]]);
  assert.ok(button.classList.contains('unread'));
});

test('one notification tap waits for the phone log layout before jumping',async t=>{
  const {window:w}=new JSDOM('<button id="boardActivityButton"></button><section id="boardActivity" hidden><p role="status"></p><ol></ol></section><iframe id="logFrame" data-ready="1"></iframe>',{url:'https://test/board/?id=room',runScripts:'outside-only'});
  t.after(()=>w.close());
  w.boardId='room';
  w.state={tool:'matrix',board:{logs:[{roomId:'log',title:'LOG'}]}};
  w.matchMedia=()=>({matches:true});
  w.openLog=async id=>Object.assign(w.state,{activeRoom:id,tool:'log'});
  const frame=w.document.querySelector('iframe');
  let jumps=0,retry;
  w.setTimeout=callback=>{retry=callback};
  frame.contentWindow.jijinOpenActivity=()=>{jumps++;return true};
  for(const file of ['public/shared/comment-target.js','public/board/board-activity.js'])w.eval(readFileSync(file,'utf8'));
  const target=w.JijinCommentTarget.log('room','log',{messageId:'line',startOffset:0,endOffset:1});
  w.dispatchEvent(new w.CustomEvent('jijinboard-activity',{detail:{kind:'comment',id:'comment',target}}));
  w.document.querySelector('#boardActivityButton').click();
  w.document.querySelector('li button').click();
  await new Promise(setImmediate);
  assert.equal(jumps,0);
  frame.dataset.phoneReady='1';
  retry();
  await new Promise(setImmediate);
  assert.equal(jumps,1);
});
